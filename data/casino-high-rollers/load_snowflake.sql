CREATE SCHEMA IF NOT EXISTS SE_DEMO_DB.CASINO;
USE SCHEMA SE_DEMO_DB.CASINO;

-- 1. Hosts (20 rows) -------------------------------------------------
CREATE OR REPLACE TABLE CASINO_HOSTS (
  HOST_ID     VARCHAR(8)  NOT NULL,          -- PK, e.g. H01
  FIRST_NAME  VARCHAR(64) NOT NULL,
  LAST_NAME   VARCHAR(64) NOT NULL,
  CONSTRAINT PK_CASINO_HOSTS PRIMARY KEY (HOST_ID)
);

-- 2. Players (200 rows — all high rollers) ---------------------------
CREATE OR REPLACE TABLE CASINO_PLAYERS (
  PLAYER_ID        VARCHAR(10) NOT NULL,     -- PK, e.g. P0001
  FIRST_NAME       VARCHAR(64) NOT NULL,
  LAST_NAME        VARCHAR(64) NOT NULL,
  DATE_OF_BIRTH    DATE        NOT NULL,
  HOST_ID          VARCHAR(8)  NOT NULL,     -- FK -> CASINO_HOSTS.HOST_ID
  BIG_WINNER_FLAG  BOOLEAN     NOT NULL,     -- convenience flag (the "few" net winners)
  CONSTRAINT PK_CASINO_PLAYERS PRIMARY KEY (PLAYER_ID),
  CONSTRAINT FK_PLAYERS_HOST FOREIGN KEY (HOST_ID) REFERENCES CASINO_HOSTS(HOST_ID)
);

-- 3. Game categories (7 rows) ----------------------------------------
CREATE OR REPLACE TABLE GAME_CATEGORIES (
  CATEGORY_ID  VARCHAR(4)  NOT NULL,         -- PK, e.g. C1
  GAME_NAME    VARCHAR(32) NOT NULL,
  CONSTRAINT PK_GAME_CATEGORIES PRIMARY KEY (CATEGORY_ID)
);

-- 4. Game plays (one row per turn) -----------------------------------
CREATE OR REPLACE TABLE CASINO_GAME_PLAYS (
  PLAY_ID      VARCHAR(12)   NOT NULL,       -- PK, e.g. T00000001
  PLAYER_ID    VARCHAR(10)   NOT NULL,       -- FK -> CASINO_PLAYERS.PLAYER_ID
  CATEGORY_ID  VARCHAR(4)    NOT NULL,       -- FK -> GAME_CATEGORIES.CATEGORY_ID
  GAME_NAME    VARCHAR(32)   NOT NULL,
  PLAYED_AT    TIMESTAMP_NTZ NOT NULL,
  AMOUNT_BET   NUMBER(12,2)  NOT NULL,
  AMOUNT_WON   NUMBER(12,2)  NOT NULL,
  CONSTRAINT PK_CASINO_GAME_PLAYS PRIMARY KEY (PLAY_ID),
  CONSTRAINT FK_PLAYS_PLAYER   FOREIGN KEY (PLAYER_ID)   REFERENCES CASINO_PLAYERS(PLAYER_ID),
  CONSTRAINT FK_PLAYS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES GAME_CATEGORIES(CATEGORY_ID)
);

